package org.jopenagent.testsupport;

/** Plain POJO fixture (no-arg constructor + fields) for ObjectBinder tests. */
public class Person {

    private String name;
    private int age;

    public Person() {
    }

    public Person(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }
}
